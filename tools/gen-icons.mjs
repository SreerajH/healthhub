// Generates src/components/healthhub/icon-shapes.ts from the Figma plugin's icon list (HH_ICONS),
// so the app draws exactly the same 24px icons as the design kit. Run: node tools/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../figma-plugin/code.js', import.meta.url), 'utf8');
function grab(name) {
  const start = src.indexOf('const ' + name + ' = {');
  const end = src.indexOf('\n};', start);
  return new Function('return ' + src.slice(start + ('const ' + name + ' = ').length, end + 3).replace(/;$/, ''))();
}
const lines = grab('HH_ICONS');
const filled = grab('HH_ICONS_FILLED');

function shapes(markup) {
  const out = [];
  const re = /<(path|circle|rect)\s([^>]*?)\/>/g;
  let m;
  while ((m = re.exec(markup))) {
    const attrs = {};
    for (const a of m[2].matchAll(/([a-z-]+)="([^"]*)"/g)) attrs[a[1]] = isNaN(Number(a[2])) ? a[2] : Number(a[2]);
    out.push([m[1], attrs]);
  }
  return out;
}

const body = [];
for (const [name, markup] of Object.entries(lines)) body.push('  ' + JSON.stringify(name) + ': { filled: false, shapes: ' + JSON.stringify(shapes(markup)) + ' },');
for (const [name, [markup]] of Object.entries(filled)) body.push('  ' + JSON.stringify(name) + ': { filled: true, shapes: ' + JSON.stringify(shapes(markup)) + ' },');

writeFileSync(new URL('../src/components/healthhub/icon-shapes.ts', import.meta.url),
  '// GENERATED by tools/gen-icons.mjs from figma-plugin/code.js (HH_ICONS). Do not edit by hand.\n' +
  '// iconsax-style Linear icons on a 24px grid, 1.5 stroke, round caps/joins — same as the Figma kit.\n\n' +
  'export type IconShape = [\'path\' | \'circle\' | \'rect\', Record<string, string | number>];\n\n' +
  'export const ICON_SHAPES = {\n' + body.join('\n') + '\n} as const satisfies Record<string, { filled: boolean; shapes: readonly IconShape[] }>;\n\n' +
  'export type IconName = keyof typeof ICON_SHAPES;\n');
console.log(Object.keys(lines).length + Object.keys(filled).length + ' icons written');
